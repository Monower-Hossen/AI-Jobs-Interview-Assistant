"""Technical assessment UI with static, non-executing code review."""

from datetime import datetime

import streamlit as st
from database import Assessment, get_db_context
from services.technical_assessment import TOPICS, TechnicalAssessmentService

from frontend.shared.components import (
    data_table,
    empty_state,
    error_state,
    kpi_row,
    page_header,
    render_score_chart,
    section,
    success_toast,
)
from frontend.user.interview_page import _ensure_user_session


def show_technical_page(embedded: bool = False) -> None:
    if not embedded:
        page_header(
            "Technical assessment",
            "Practice coding and system-design questions with static AI review",
            ":material/code:",
        )
        st.info(
            "Submitted code is never executed on the application server. Feedback is generated by an "
            "AI model and is advisory only.",
            icon=":material/shield:",
        )

    with st.container(border=True):
        col1, col2, col3 = st.columns([2, 1, 1])
        with col1:
            topic = st.selectbox("Topic", TOPICS)
        with col2:
            difficulty = st.segmented_control(
                "Difficulty",
                ["easy", "medium", "hard"],
                default="medium",
                key="technical_difficulty_control",
            )
        with col3:
            count = st.number_input("Questions", 1, 5, 3, key="technical_question_count")
        if st.button(
            "Generate assessment", type="primary", icon=":material/auto_awesome:", width="stretch"
        ):
            try:
                with st.spinner("Creating assessment…"):
                    questions = TechnicalAssessmentService().generate(
                        topic, difficulty or "medium", count
                    )
            except Exception as exc:
                error_state("Assessment generation failed.", str(exc))
                return
            else:
                st.session_state.assessment_questions = [q.model_dump() for q in questions]
                st.session_state.assessment_answers = {}
                st.session_state.assessment_feedback = {}
                st.session_state.assessment_topic = topic
                st.session_state.assessment_difficulty = difficulty
                success_toast("Assessment ready.")

    questions = st.session_state.get("assessment_questions", [])
    if not questions:
        _render_history()
        return

    service = TechnicalAssessmentService()
    total = len(questions)
    scores = []
    for index, raw in enumerate(questions, 1):
        section(f"Question {index} of {total}", ":material/quiz:")
        with st.container(border=True):
            st.markdown(f"**{raw['prompt']}**")
            st.caption("Expected concepts: " + ", ".join(raw.get("expected_concepts", [])))
            language = raw.get("language", "python")
            if raw.get("starter_code"):
                st.code(raw["starter_code"], language=language)
            answer = st.text_area(
                "Your solution",
                height=220,
                key=f"assessment_answer_{index}",
                placeholder="Write code or explain your reasoning…",
            )
            if st.button(
                "Evaluate answer", type="primary", key=f"assessment_submit_{index}", width="stretch"
            ):
                if not answer.strip():
                    st.warning("Provide an answer before evaluating.")
                else:
                    from services.technical_assessment import AssessmentQuestion

                    try:
                        with st.spinner("Reviewing your solution…"):
                            question = AssessmentQuestion(**raw)
                            feedback = service.evaluate(question, answer)
                    except Exception as exc:
                        error_state("Evaluation failed.", str(exc))
                    else:
                        st.session_state.assessment_answers[index] = answer
                        st.session_state.assessment_feedback[index] = feedback.model_dump()
                        success_toast("Feedback ready.")

        feedback_data = st.session_state.assessment_feedback.get(index)
        if feedback_data:
            _render_feedback(feedback_data, language)
            scores.append(feedback_data["score"])

    if len(scores) == total and st.button(
        "Save assessment result", type="primary", width="stretch"
    ):
        _save_assessment(questions)
        success_toast("Assessment saved to your history.")
    _render_history()


def _render_feedback(feedback: dict, language: str = "python") -> None:
    render_score_chart(feedback.get("dimensions", {}), "Technical assessment scores")
    st.metric("Overall", f"{feedback['score']:.1f}/10", border=True)
    col1, col2 = st.columns(2)
    with col1:
        st.markdown("**Time complexity:** " + str(feedback.get("time_complexity") or "Not stated"))
        st.markdown(
            "**Space complexity:** " + str(feedback.get("space_complexity") or "Not stated")
        )
    with col2:
        st.markdown("**Strengths**")
        for item in feedback.get("strengths", []):
            st.markdown(f"- {item}")
    st.markdown("**Issues**")
    for item in feedback.get("issues", []):
        st.markdown(f"- {item}")
    with st.expander("Explanation and improved solution"):
        st.write(feedback.get("explanation", ""))
        st.code(feedback.get("improved_solution", ""), language=language)


def _save_assessment(questions: list[dict]) -> None:
    answers = st.session_state.assessment_answers
    feedback = st.session_state.assessment_feedback
    score = sum(item["score"] for item in feedback.values()) / len(feedback)
    session_id = _ensure_user_session()
    with get_db_context() as db:
        db.add(
            Assessment(
                session_id=session_id,
                topic=st.session_state.get("assessment_topic", "Technical"),
                difficulty=st.session_state.get("assessment_difficulty", "medium"),
                questions=questions,
                answers=[answers.get(i, "") for i in range(1, len(questions) + 1)],
                feedback=[feedback.get(i, {}) for i in range(1, len(questions) + 1)],
                score=score,
                max_score=10.0,
                status="completed",
                completed_at=datetime.now(),
            )
        )


def _render_history() -> None:
    section("Assessment history", ":material/history:")
    session_id = _ensure_user_session()
    with get_db_context() as db:
        rows = (
            db.query(Assessment)
            .filter(Assessment.session_id == session_id, Assessment.status == "completed")
            .order_by(Assessment.created_at.desc())
            .limit(20)
            .all()
        )
        history = [
            {
                "Topic": row.topic,
                "Difficulty": row.difficulty,
                "Score": f"{row.score:.1f}/10",
                "Questions": len(row.questions or []),
                "Date": row.created_at.strftime("%Y-%m-%d") if row.created_at else "",
            }
            for row in rows
        ]
    if not history:
        empty_state("No completed assessments yet.")
    else:
        kpi_row([("Completed assessments", len(history), None)])
        data_table(history)
